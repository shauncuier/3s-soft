function escape(path: string): string {
  return path.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
}

/** Builds the Apache config for cPanel shared hosting. Written to public/.htaccess before every build. */
export function renderHtaccess(list: Redirect[]): string {
  const rules = [
    ...list.map((r) => `RedirectMatch 301 ^${escape(r.from)}/?$ ${r.to}`),
    'RedirectMatch 301 ^/dashboard(/.*)?$ /',
    'RedirectMatch 301 ^/blog/?$ /blogs/',
  ]
  return `# Generated by scripts/build-htaccess.ts from src/content/redirects.ts. Do not edit by hand.
Options -MultiViews -Indexes
DirectoryIndex index.html
ErrorDocument 404 /404.html

<IfModule mod_rewrite.c>
  RewriteEngine On
  RewriteBase /
  # www goes to the bare production domain
  RewriteCond %{HTTP_HOST} ^www\\.3s-soft\\.com$ [NC]
  RewriteRule ^ https://3s-soft.com%{REQUEST_URI} [L,R=301]
  # HTTPS on whatever host was asked for, so a staging subdomain stays on staging
  RewriteCond %{HTTPS} off
  RewriteRule ^ https://%{HTTP_HOST}%{REQUEST_URI} [L,R=301]
  # Folder URLs end with a slash (matches trailingSlash: true in the build)
  RewriteCond %{REQUEST_FILENAME} -d
  RewriteCond %{REQUEST_URI} !/$
  RewriteRule ^(.*)$ https://%{HTTP_HOST}/$1/ [L,R=301]
</IfModule>

# Permanent redirects for removed and moved pages
${rules.join('\n')}

<IfModule mod_headers.c>
  Header always set X-Content-Type-Options "nosniff"
  Header always set Referrer-Policy "strict-origin-when-cross-origin"
  Header always set X-Frame-Options "SAMEORIGIN"
  Header always set Permissions-Policy "camera=(), microphone=(), geolocation=()"
  <FilesMatch "\\.(html|xml|txt)$">
    Header set Cache-Control "no-cache"
  </FilesMatch>
  <If "%{REQUEST_URI} =~ m#^/_next/static/#">
    Header set Cache-Control "public, max-age=31536000, immutable"
  </If>
  <FilesMatch "\\.(webp|png|jpe?g|svg|ico|woff2?|js)$">
    Header set Cache-Control "public, max-age=2592000"
  </FilesMatch>
</IfModule>

<IfModule mod_brotli.c>
  AddOutputFilterByType BROTLI_COMPRESS text/html text/css text/plain text/xml text/javascript application/javascript application/json application/xml image/svg+xml
</IfModule>
<IfModule mod_deflate.c>
  AddOutputFilterByType DEFLATE text/html text/css text/plain text/xml text/javascript application/javascript application/json application/xml image/svg+xml
</IfModule>

<Files "sitemap.xml">
  ForceType application/xml
</Files>
`
}
